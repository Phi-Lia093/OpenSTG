#!/usr/bin/env python3
"""Turn tools/i18n.csv into the i18n.hpp the sources include.

The CSV is the original's own string table: one row per message, with the address it
lived at in the retail binary, the text, and the macro the source uses.

    address|text|name
    00497b9c|東方妖々夢　～ Perfect Cherry Blossom. ver 1.00b|TH_WINDOW_TITLE

Every name becomes a `const char *` holding the text as a C literal. Escape sequences
already present in the CSV (`\\r\\n`) are kept as escapes rather than being expanded:
the source passes these strings to Win32 and to printf-style formatters, and those want
the escape in the literal.

    python tools/generate_i18n.py                        # tools/i18n.csv -> build/generated
    python tools/generate_i18n.py CSV OUT.hpp            # explicit paths
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

DEFAULT_CSV = "i18n.csv"
OUTPUT = "i18n.hpp"


def c_literal(text: str) -> str:
    """Quote CSV text as a C string literal.

    Backslashes are NOT doubled: the CSV stores `\\r\\n` meaning "carriage return,
    newline", which is exactly what the C compiler should see. Doubling them would put
    a literal backslash-r into a window title.

    Only `"` is escaped. Backslashes are deliberately left alone: the CSV already holds
    `\\r\\n` as the two-character escape the compiler should interpret, so doubling them
    would hand Win32 the literal text `\r\n` instead of a carriage return.
    """
    out = []
    for ch in text:
        if ch == '"':
            out.append('\\"')
        elif ch == "\n":
            # A real newline in the CSV would end the literal; none exist today, but a
            # generated header that silently breaks on one is worse than the check.
            raise ValueError("unescaped newline in message text")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def generate(csv_path: Path, header_path: Path) -> int:
    rows = []
    with csv_path.open(encoding="utf-8", newline="") as stream:
        reader = csv.reader(stream, delimiter="|")
        header = next(reader, None)
        if header is None or header[:3] != ["address", "text", "name"]:
            raise ValueError(f"{csv_path}: unexpected header {header}")
        for line_number, row in enumerate(reader, start=2):
            if not row or not any(field.strip() for field in row):
                continue
            # The CSV carries prose comments, e.g. a note that one message really does
            # end with "n" instead of a newline escape. They are not rows.
            if row[0].lstrip().startswith("#"):
                continue
            if len(row) < 3:
                raise ValueError(f"{csv_path}:{line_number}: expected three fields")
            address, text, name = row[0].strip(), row[1], row[2].strip()
            if not name.startswith("TH_"):
                raise ValueError(f"{csv_path}:{line_number}: bad macro name {name!r}")
            rows.append((address, text, name))

    seen = set()
    lines = [
        f"// Generated by tools/generate_i18n.py from {csv_path.name}.",
        "// Edit the CSV, not this file.",
        "#pragma once",
        "",
    ]
    for address, text, name in rows:
        if name in seen:
            raise ValueError(f"duplicate message macro {name}")
        seen.add(name)
        lines.append(f"// {address}")
        lines.append(f"static const char *{name} = {c_literal(text)};")
    lines.append("")

    header_path.parent.mkdir(parents=True, exist_ok=True)
    header_path.write_text("\n".join(lines), encoding="utf-8")
    return len(rows)


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    csv_path = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "tools" / DEFAULT_CSV
    header_path = (Path(sys.argv[2]) if len(sys.argv) > 2
                   else root / "build/generated" / OUTPUT)
    count = generate(csv_path, header_path)
    print(f"{header_path}: {count} messages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
